/**
 * `pnpm --filter @medibooker/i18n generate` scans `src/messages/` and writes the catalogue and the
 * list of languages (05 §2.1), both committed: a new language is one JSON file plus this script.
 */
import { mkdirSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const PACKAGE_ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const MESSAGES_DIR = join(PACKAGE_ROOT, 'src/messages');
export const CATALOG_FILE = join(PACKAGE_ROOT, 'src/generated/catalog.ts');
export const LOCALES_FILE = join(PACKAGE_ROOT, 'locales.json');

/** Arabic is the default language and the source of the `Messages` type. */
const SOURCE_LOCALE = 'ar';

/** The languages of a list of file names: the source first, then in alphabetical order. */
export function localesOf(fileNames: readonly string[]): readonly string[] {
  const locales = fileNames
    .filter((name) => name.endsWith('.json'))
    .map((name) => name.slice(0, -'.json'.length))
    .sort();
  if (!locales.includes(SOURCE_LOCALE)) throw new Error(`Missing ${SOURCE_LOCALE}.json`);
  return [SOURCE_LOCALE, ...locales.filter((locale) => locale !== SOURCE_LOCALE)];
}

/** An import name: `pt-BR` becomes `pt_BR`. */
const identifierOf = (locale: string): string => locale.replaceAll('-', '_');

export function buildCatalog(locales: readonly string[]): string {
  const imports = locales.map(
    (locale) =>
      `import ${identifierOf(locale)} from '../messages/${locale}.json' with { type: 'json' };`,
  );
  const tuple = locales.map((locale) => `'${locale}'`).join(', ');
  const entries = locales.map((locale) => {
    const name = identifierOf(locale);
    return name === locale ? `  ${name},` : `  '${locale}': ${name},`;
  });
  return [
    '// Generated by scripts/generate.ts from src/messages/. Do not edit.',
    ...imports,
    '',
    `export const LOCALES = [${tuple}] as const;`,
    '',
    `/** Arabic is the source: a language that differs from it does not compile. */`,
    `export type Messages = typeof ${identifierOf(SOURCE_LOCALE)};`,
    '',
    'export const messages = {',
    ...entries,
    '} satisfies Record<(typeof LOCALES)[number], Messages>;',
    '',
  ].join('\n');
}

export function buildLocalesJson(locales: readonly string[]): string {
  return `${JSON.stringify(locales)}\n`;
}

if (import.meta.main) {
  const locales = localesOf(readdirSync(MESSAGES_DIR));
  mkdirSync(dirname(CATALOG_FILE), { recursive: true });
  writeFileSync(CATALOG_FILE, buildCatalog(locales));
  writeFileSync(LOCALES_FILE, buildLocalesJson(locales));
  process.stdout.write(`generate: ${locales.join(', ')}\n`);
}
