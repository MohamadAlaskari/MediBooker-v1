/**
 * `pnpm --filter @medibooker/design-tokens generate` turns the DTCG files in tokens/ into
 * css/tokens.css (a Tailwind v4 stylesheet) and src/generated/tokens.ts (05 §3.1). Both are
 * committed, and `pnpm check:drift` fails when they differ from this build.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const PACKAGE_ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const CSS_FILE = join(PACKAGE_ROOT, 'css/tokens.css');
export const TS_FILE = join(PACKAGE_ROOT, 'src/generated/tokens.ts');

const HEADER = 'Generated by scripts/build-tokens.ts from tokens/. Do not edit.';
const BRAND_PRESET_NAMES = ['teal', 'ocean', 'indigo', 'violet', 'graphite'] as const;
const REM = 16;

interface Measure {
  readonly value: number;
  readonly unit: string;
}
interface Shadow {
  readonly color: string;
  readonly offsetX: Measure;
  readonly offsetY: Measure;
  readonly blur: Measure;
  readonly spread: Measure;
}
interface TextStyle {
  readonly fontFamily: string;
  readonly fontSize: Measure;
  readonly fontWeight: string;
  readonly letterSpacing: Measure;
  readonly lineHeight: string;
}

/** One token of a DTCG file, by its dotted path. Only build-time code sees this shape. */
type Tokens = ReadonlyMap<string, unknown>;

/** Walks a DTCG group: keys with `$` belong to the DTCG format, the others are children. */
function flatten(group: Record<string, unknown>, path: string, into: Map<string, unknown>): void {
  if ('$value' in group) {
    into.set(path, group.$value);
    return;
  }
  for (const [key, child] of Object.entries(group)) {
    if (key.startsWith('$')) continue;
    flatten(child as Record<string, unknown>, path === '' ? key : `${path}.${key}`, into);
  }
}

function read(file: string): Tokens {
  const text = readFileSync(join(PACKAGE_ROOT, 'tokens', `${file}.json`), 'utf8');
  const tokens = new Map<string, unknown>();
  flatten(JSON.parse(text) as Record<string, unknown>, '', tokens);
  return tokens;
}

/** The target of an alias such as `{gray.50}`; undefined for a plain value. */
function aliasOf(value: unknown): string | undefined {
  return typeof value === 'string' ? /^\{(.+)\}$/.exec(value)?.[1] : undefined;
}

function required(tokens: Tokens, path: string): unknown {
  if (!tokens.has(path)) throw new Error(`Unknown token ${path}`);
  return tokens.get(path);
}

function targetOf(value: unknown): string {
  const target = aliasOf(value);
  if (target === undefined) throw new Error(`Expected an alias, got ${JSON.stringify(value)}`);
  return target;
}

const rem = (px: number): string => `${String(px / REM)}rem`;
const px = (value: number): string => `${String(value)}px`;
const varName = (path: string): string => `--${path.replaceAll('.', '-')}`;
const lastSegment = (path: string): string => path.slice(path.lastIndexOf('.') + 1);
const camelCase = (name: string): string =>
  name.replace(/-([a-z0-9])/g, (_, letter: string) => letter.toUpperCase());

function entriesOf(tokens: Tokens, prefix: string): [string, unknown][] {
  return [...tokens].filter(([path]) => path.startsWith(`${prefix}.`));
}

function block(selector: string, lines: readonly string[]): string {
  const body = lines.map((line) => (line === '' ? '' : `  ${line}`)).join('\n');
  return `${selector} {\n${body}\n}\n`;
}

function media(query: string, inner: string): string {
  const body = inner
    .trimEnd()
    .split('\n')
    .map((line) => `  ${line}`)
    .join('\n');
  return `@media ${query} {\n${body}\n}\n`;
}

/** The custom properties of a colour mode, each a reference to a primitive or a brand step. */
function colorDeclarations(mode: Tokens): string[] {
  return [...mode].map(([path, value]) => `${varName(path)}: var(${varName(targetOf(value))});`);
}

function fontStack(families: readonly string[]): string {
  return families
    .map((family) => {
      if (family === 'sans-serif') return family;
      // next/font hands out a generated family name through a variable (03 §9).
      const variable = `--font-${family.toLowerCase().replaceAll(' ', '-')}`;
      return `var(${variable}, '${family}')`;
    })
    .join(', ');
}

/** Set per :lang(), so that a passage in another language gets its own stack and line heights. */
function typographyDeclarations(mode: Tokens): string[] {
  return [
    `--font-sans: ${fontStack(required(mode, 'font.family.sans') as readonly string[])};`,
    ...entriesOf(mode, 'font.line-height').map(
      ([path, value]) =>
        `--text-${lastSegment(path)}--line-height: ${rem((value as Measure).value)};`,
    ),
  ];
}

function shadowValue(layers: readonly Shadow[]): string {
  return layers
    .map(
      (layer) =>
        `${px(layer.offsetX.value)} ${px(layer.offsetY.value)} ${px(layer.blur.value)} ${px(layer.spread.value)} ${layer.color}`,
    )
    .join(', ');
}

function bezier(points: readonly number[]): string {
  return `cubic-bezier(${points.join(', ')})`;
}

function buildCss(): string {
  const primitives = read('primitives');
  const dimension = read('dimension');
  const layout = read('layout');
  const english = read('typography.english');
  const arabic = read('typography.arabic');
  const textStyles = read('text-styles');
  const elevation = read('elevation');
  const motion = read('motion');
  const light = read('color.light');
  const dark = read('color.dark');

  const theme = [
    // Only token utilities exist: Tailwind's own scales are gone (03 §9).
    ...[
      'color',
      'spacing',
      'radius',
      'text',
      'font',
      'font-weight',
      'leading',
      'tracking',
      'shadow',
      'ease',
      'container',
      'breakpoint',
    ].map((namespace) => `--${namespace}-*: initial;`),
    '',
    ...entriesOf(layout, 'breakpoint').map(
      ([path, value]) => `${varName(path)}: ${rem((value as Measure).value)};`,
    ),
    ...entriesOf(layout, 'container').map(
      ([path, value]) => `${varName(path)}: ${rem((value as Measure).value)};`,
    ),
    '',
    ...entriesOf(dimension, 'spacing').map(
      ([path, value]) => `${varName(path)}: ${rem((value as Measure).value)};`,
    ),
    ...entriesOf(layout, 'size').map(
      ([path, value]) => `--spacing-${lastSegment(path)}: ${rem((value as Measure).value)};`,
    ),
    ...entriesOf(dimension, 'radius').map(
      ([path, value]) => `${varName(path)}: ${px((value as Measure).value)};`,
    ),
    '',
    `--font-sans: ${fontStack(required(english, 'font.family.sans') as readonly string[])};`,
    ...entriesOf(english, 'font.style').map(
      ([path, value]) => `--font-weight-${lastSegment(path)}: ${String(value)};`,
    ),
    '',
    ...[...textStyles].flatMap(([path, value]) => {
      const style = value as TextStyle;
      const name = lastSegment(path);
      return [
        `--text-${name}: ${rem(style.fontSize.value)};`,
        `--text-${name}--line-height: ${rem((required(english, targetOf(style.lineHeight)) as Measure).value)};`,
        `--text-${name}--font-weight: var(--font-weight-${lastSegment(targetOf(style.fontWeight))});`,
      ];
    }),
    '',
    ...[...elevation].map(
      ([path, value]) =>
        `--shadow-elevation-${lastSegment(path)}: ${shadowValue(value as readonly Shadow[])};`,
    ),
    '',
    ...entriesOf(motion, 'motion.ease').map(
      ([path]) => `--ease-${lastSegment(path)}: var(${varName(path)});`,
    ),
    '--default-transition-duration: var(--motion-duration-base);',
    '--default-transition-timing-function: var(--motion-ease-standard);',
    '',
    ...colorDeclarations(light),
  ];

  const plain = [
    ...[...primitives].map(([path, value]) => `${varName(path)}: ${String(value)};`),
    '',
    ...[...read('brand.teal')].map(
      ([path, value]) => `${varName(path)}: ${String(required(primitives, targetOf(value)))};`,
    ),
    '',
    ...entriesOf(dimension, 'border-width').map(
      ([path, value]) => `${varName(path)}: ${px((value as Measure).value)};`,
    ),
    '',
    ...entriesOf(motion, 'motion.duration').map(
      ([path, value]) => `${varName(path)}: ${String((value as Measure).value)}ms;`,
    ),
    ...entriesOf(motion, 'motion.ease').map(
      ([path, value]) => `${varName(path)}: ${bezier(value as readonly number[])};`,
    ),
  ];

  const presets = BRAND_PRESET_NAMES.filter((name) => name !== 'teal').map((name) =>
    block(
      `[data-brand='${name}']`,
      [...read(`brand.${name}`)].map(
        ([path, value]) => `${varName(path)}: ${String(required(primitives, targetOf(value)))};`,
      ),
    ),
  );

  const darkLines = ['color-scheme: dark;', ...colorDeclarations(dark)];

  return [
    `/* ${HEADER} */\n`,
    block('@theme static', theme),
    block(':root', plain),
    ...presets,
    block("[data-theme='dark']", darkLines),
    media('(prefers-color-scheme: dark)', block("[data-theme='system']", darkLines)),
    block(':root,\n:lang(en)', typographyDeclarations(english)),
    block(':lang(ar)', typographyDeclarations(arabic)),
  ].join('\n');
}

/** A colour for TypeScript: the hex value, or the step of the practice's brand scale. */
function colorValue(primitives: Tokens, value: unknown): string | { brand: number } {
  const target = targetOf(value);
  if (target.startsWith('brand.')) return { brand: Number(lastSegment(target)) };
  return required(primitives, target) as string;
}

function nest(entries: readonly (readonly [string, unknown])[]): Record<string, unknown> {
  const root: Record<string, unknown> = {};
  for (const [path, value] of entries) {
    const segments = path.split('.').map(camelCase);
    const leaf = segments.pop() ?? '';
    let group = root;
    for (const segment of segments) {
      group[segment] ??= {};
      group = group[segment] as Record<string, unknown>;
    }
    group[leaf] = value;
  }
  return root;
}

function constant(name: string, comment: string, value: unknown): string {
  return `/** ${comment} */\nexport const ${name} = ${JSON.stringify(value, null, 2)} as const;\n`;
}

function buildTypography(mode: Tokens, textStyles: Tokens): Record<string, unknown> {
  const stack = required(mode, 'font.family.sans') as readonly string[];
  const family = stack[0];
  return {
    fontStack: stack.map((name) => (name === 'sans-serif' ? name : `"${name}"`)).join(', '),
    styles: Object.fromEntries(
      [...textStyles].map(([path, value]) => {
        const style = value as TextStyle;
        return [
          camelCase(lastSegment(path)),
          {
            fontFamily: family,
            fontSize: style.fontSize.value,
            lineHeight: (required(mode, targetOf(style.lineHeight)) as Measure).value,
            fontWeight: required(mode, targetOf(style.fontWeight)) as number,
            letterSpacing: style.letterSpacing.value,
          },
        ];
      }),
    ),
  };
}

function measures(tokens: Tokens, prefix: string): Record<string, number> {
  return Object.fromEntries(
    entriesOf(tokens, prefix).map(([path, value]) => [
      camelCase(lastSegment(path)),
      (value as Measure).value,
    ]),
  );
}

function buildTs(): string {
  const primitives = read('primitives');
  const dimension = read('dimension');
  const layout = read('layout');
  const textStyles = read('text-styles');
  const motion = read('motion');
  const colors = (mode: string): unknown =>
    nest(
      [...read(`color.${mode}`)].map(([path, value]) => [
        path.slice('color.'.length),
        colorValue(primitives, value),
      ]),
    );

  const brandPresets = Object.fromEntries(
    BRAND_PRESET_NAMES.map((name) => [
      name,
      Object.fromEntries(
        [...read(`brand.${name}`)].map(([path, value]) => [
          lastSegment(path),
          required(primitives, targetOf(value)) as string,
        ]),
      ),
    ]),
  );

  const elevation = Object.fromEntries(
    [...read('elevation')].map(([path, value]) => [
      lastSegment(path),
      (value as readonly Shadow[]).map((layer) => ({
        color: layer.color,
        offsetX: layer.offsetX.value,
        offsetY: layer.offsetY.value,
        blur: layer.blur.value,
        spread: layer.spread.value,
      })),
    ]),
  );

  return [
    `// ${HEADER}\n`,
    constant('BRAND_PRESETS', 'The brand scale of every preset, by step.', brandPresets),
    constant(
      'COLOR_TOKENS',
      'The semantic colours per scheme: a hex value, or a step of the brand scale.',
      { light: colors('light'), dark: colors('dark') },
    ),
    constant('spacing', 'Spacing in px.', measures(dimension, 'spacing')),
    constant('radius', 'Corner radii in px.', measures(dimension, 'radius')),
    constant('borderWidth', 'Border widths in px.', measures(dimension, 'border-width')),
    constant('breakpoints', 'Web layout breakpoints in px.', measures(layout, 'breakpoint')),
    constant(
      'sizes',
      'Fixed sizes in px; nothing tappable is smaller than touchTarget.',
      measures(layout, 'size'),
    ),
    constant('elevation', 'Shadow layers in px.', elevation),
    constant('typography', 'Text styles per locale, sizes in px.', {
      en: buildTypography(read('typography.english'), textStyles),
      ar: buildTypography(read('typography.arabic'), textStyles),
    }),
    constant('motion', 'Durations in ms, eases as cubic-bezier control points.', {
      duration: measures(motion, 'motion.duration'),
      ease: Object.fromEntries(
        entriesOf(motion, 'motion.ease').map(([path, value]) => [lastSegment(path), value]),
      ),
    }),
  ].join('\n');
}

export function buildTokens(): { readonly css: string; readonly ts: string } {
  return { css: buildCss(), ts: buildTs() };
}

if (import.meta.main) {
  const { css, ts } = buildTokens();
  for (const [file, content] of [
    [CSS_FILE, css],
    [TS_FILE, ts],
  ] as const) {
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, content);
    console.log(`build-tokens: wrote ${file}`);
  }
}
